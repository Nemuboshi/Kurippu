#!/usr/bin/env bash
# Regenerate src/ffi/mpv_generated.rs from the installed libmpv headers.
#
# This file is DERIVED, not transcribed. Hand-writing the mpv enums and structs
# for this crate produced at least seven silent errors, and the layout
# assertions written alongside them did not catch any, because both came from
# the same wrong reading of the headers:
#
#   mpv_node                     field order (u precedes format)
#   mpv_node_list                field order (values precedes keys)
#   mpv_byte_array               field order (data precedes size)
#   MPV_FORMAT_FLAG and onward   every discriminant off by one
#   MPV_EVENT_PROPERTY_CHANGE    22, not 20
#   MPV_ERROR_PROPERTY_NOT_FOUND -8, not -11
#   MPV_ERROR_COMMAND            -12, not -6
#   MPV_RENDER_PARAM_SW_POINTER  20, not 8
#
# Every one of those compiles happily and corrupts at runtime. Regenerate
# rather than repair, and never edit the output by hand.
#
# Needs bindgen (apt: bindgen libclang-dev) as a maintenance-time tool only.
# build.rs does NOT invoke it, so CI and contributors need no libclang.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
mkdir -p "${here}/src/ffi"
out="${here}/src/ffi/mpv_generated.rs"

TYPES=(
  mpv_node mpv_node_list mpv_byte_array mpv_render_param mpv_event
  mpv_event_property mpv_format mpv_event_id mpv_render_param_type
  mpv_opengl_init_params mpv_opengl_fbo mpv_render_context mpv_handle mpv_error
)

FUNCS=(
  mpv_create mpv_initialize mpv_terminate_destroy mpv_set_option_string
  mpv_observe_property mpv_command mpv_set_property mpv_get_property
  mpv_get_property_string mpv_free mpv_free_node_contents mpv_wait_event
  mpv_event_name mpv_error_string mpv_set_wakeup_callback
  mpv_render_context_create mpv_render_context_free
  mpv_render_context_set_update_callback mpv_render_context_update
  mpv_render_context_render
)

args=()
for t in "${TYPES[@]}"; do args+=(--allowlist-type "$t"); done
for f in "${FUNCS[@]}"; do args+=(--allowlist-function "$f"); done

bindgen /usr/include/mpv/render.h -o "$out" "${args[@]}" -- -I/usr/include

# The generated doc attributes are verbatim copies of the header comments and
# dwarf the declarations; drop them but keep bindgen's layout assertions.
sed -i '/#\[doc *=/d; /^ *#!\[doc/d' "$out"

tmp="$(mktemp)"
{
  echo "// @generated by ffi/regenerate.sh -- do not edit by hand."
  echo "// See that script for why this module is derived, not transcribed."
  cat "$out"
} > "$tmp" && mv "$tmp" "$out"

wc -l "$out"
